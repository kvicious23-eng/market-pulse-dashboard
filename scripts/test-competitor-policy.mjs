import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),m=require('../chrome-extension/competitor-models.js');
const url='https://www.coupang.com/vp/products/1?itemId=2&vendorItemId=3';
const a={brand:'A',mtm:'A1',enabled:true,competitors:[{model:'Other',url,note:'16GB',enabled:true}]};
assert.equal(m.targets([a,{...a,mtm:'A2'}]).length,1);
assert.equal(m.targets([{...a,enabled:false}]).length,0);
assert.equal(m.targets([{...a,competitors:[{...a.competitors[0],enabled:false}]}]).length,0);
assert.equal(m.targets([a])[0].srp,null);assert.equal(m.targets([a])[0].minimumPrice,10000);
assert.equal(m.identity(url+'&tracking=ignored').key,'1-2-3');
assert.notEqual(m.identity(url).key,m.identity(url.replace('vendorItemId=3','vendorItemId=4')).key);
for(const bad of [url.replace('https:','http:'),url.replace('www.coupang.com','evil.test'),url+'&itemId=7',url.replace('vendorItemId=3',''),url.replace('www.coupang.com','user@www.coupang.com'),url.replace('products/1','products/1/extra')])assert.throws(()=>m.identity(bad));
assert.throws(()=>m.links({...a,competitors:[...a.competitors,...a.competitors]}),/중복/);
assert.throws(()=>m.links({...a,competitors:[{model:'',url}]}));
const cleaned=m.clean({...a,skuId:'0123',srp:100,danawaUrl:'old',enuriUrl:'old',naverUrl:'old'});
assert.equal(cleaned.skuId,'0123');assert.equal(cleaned.srp,100);assert.equal('danawaUrl' in cleaned,false);
assert.equal(m.capacity([a]).total,2);
console.log('Coupang identity, shared-target dedup, seller/option separation, optional/disabled links, metadata preservation and capacity passed.');
